#!/usr/bin/env python3
"""Generate include/lavender-metal/a5xx.hpp from Mesa's a5xx.xml and adreno_pm4.xml.

    python3 tools/gen_a5xx.py [A5XX_XML] [PM4_XML] [OUT_HPP]

The XML files are Mesa's (MIT), kept under refs/ext (not committed). The names are Mesa's: REG_A5XX_* are dword
register offsets (multiply by 4 for the byte offset into the GPU block at 0x05000000), A5XX_<REG>_<FIELD>__MASK /
__SHIFT are bitfields, CP_* packet opcodes come from adreno_pm4.xml. Generated, not edited.
"""
import sys
import xml.etree.ElementTree as ET

NS = "{http://nouveau.freedesktop.org/}"
A5XX = sys.argv[1] if len(sys.argv) > 1 else "refs/ext/a5xx.xml"
PM4 = sys.argv[2] if len(sys.argv) > 2 else "refs/ext/adreno_pm4.xml"
OUT = sys.argv[3] if len(sys.argv) > 3 else "userland/include/lavender-metal/a5xx.hpp"


def num(s):
    return int(s, 0)


def bitfield_lines(prefix, node, out):
    for b in node.findall(NS + "bitfield"):
        name = b.get("name")
        if b.get("pos") is not None:
            lo = hi = num(b.get("pos"))
        else:
            lo, hi = num(b.get("low")), num(b.get("high"))
        mask = ((1 << (hi - lo + 1)) - 1) << lo
        out.append(f"inline constexpr uint32_t {prefix}_{name}__MASK = 0x{mask:08x};")
        out.append(f"inline constexpr uint32_t {prefix}_{name}__SHIFT = {lo};")


def main():
    out = [
        "// Generated by tools/gen_a5xx.py from Mesa's a5xx.xml and adreno_pm4.xml (MIT). Do not edit.",
        "// REG_* are dword register offsets: byte offset = REG * 4 from the GPU block (0x05000000 on SDM660).",
        "#pragma once",
        "#include <cstdint>",
        "namespace lavender::a5xx {",
        "",
    ]
    root = ET.parse(A5XX).getroot()
    nregs = 0
    for e in root.findall(NS + "enum"):
        out.append(f"// enum {e.get('name')}")
        for v in e.findall(NS + "value"):
            out.append(f"inline constexpr uint32_t {v.get('name')} = {v.get('value')};")
    for d in root.findall(NS + "domain"):
        dname = d.get("name")
        if dname != "A5XX":
            continue
        bitsets = {bs.get("name"): bs for bs in d.findall(NS + "bitset")}
        for bs in bitsets.values():
            out.append(f"// bitset {bs.get('name')}")
            bitfield_lines(bs.get("name"), bs, out)
        for r in d.findall(NS + "reg32") + d.findall(NS + "reg64"):
            name = r.get("name")
            out.append(f"inline constexpr uint32_t REG_A5XX_{name} = {r.get('offset')};")
            nregs += 1
            bitfield_lines(f"A5XX_{name}", r, out)
            if r.get("type") in bitsets:  # a register whose fields live in a shared bitset
                bitfield_lines(f"A5XX_{name}", bitsets[r.get("type")], out)
    out.append("")
    out.append("// PM4 type 3 opcodes (adreno_pm4.xml)")
    root = ET.parse(PM4).getroot()
    for e in root.findall(NS + "enum"):
        if e.get("name") in ("adreno_pm4_type3_packets",):
            for v in e.findall(NS + "value"):
                if v.get("name", "").startswith(("CP_", "IN_")):
                    out.append(f"inline constexpr uint32_t {v.get('name')} = {v.get('value')};")
    out.append("")
    out.append("}  // namespace lavender::a5xx")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{OUT}: {nregs} registers, {len(out)} lines")


main()
